// Writes src/_icons.scss: .ico-<name> classes for the Bootstrap Icons the pages use, as CSS masks
// (so they take the text colour). Add a name here to make another icon available.
const fs = require("fs");
const names = ["trash3", "arrow-up", "arrow-down", "x-lg", "layout-sidebar", "zoom-in", "zoom-out",
  "chevron-double-left", "chevron-left", "chevron-right", "chevron-double-right", "arrow-clockwise", "copy", "download"];
let out = "// Generated by icons.js. Do not edit.\n/*! Bootstrap Icons v" + require("bootstrap-icons/package.json").version + " | MIT License | https://icons.getbootstrap.com */\n" +
  ".ico{display:inline-block;width:1em;height:1em;vertical-align:-.125em;background-color:currentColor;" +
  "-webkit-mask:var(--ico) center/contain no-repeat;mask:var(--ico) center/contain no-repeat}\n";
for (const n of names) {
  const svg = fs.readFileSync(require.resolve(`bootstrap-icons/icons/${n}.svg`), "utf8")
    .replace(/\s*class="[^"]*"/, "").replace(/\s*(width|height|fill)="[^"]*"/g, "").replace(/\s+/g, " ").trim();
  out += `.ico-${n}{--ico:url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%22/g, "'").replace(/%2F/g, "/").replace(/%3A/g, ":")}")}\n`;
}
fs.writeFileSync("src/_icons.scss", out);
