# Embed the web UI (../SD) in the firmware, gzipped, so a firmware image always carries the UI that
# matches it. Writes $PROJECT_WORKSPACE_DIR/generated/webui/webui_embedded.h (never committed) and
# defines IOTAWATT_EMBED_WEBUI. The gzip is deterministic (mtime 0), and the header is only rewritten
# when its content changes, so unchanged UI files don't force a rebuild.
Import("env")
import gzip, hashlib, os

# favicon.ico (65 KB, already compressed) stays on the SD card: costs 63 KB embedded, breaks nothing if absent.
FILES = [                                   # (SD file, content type)
    ("index.htm",    "text/html"),
    ("edit.htm",     "text/html"),
    ("graph2.htm",   "text/html"),
    ("graph2.js",    "application/javascript"),
    ("cnfstyle.css", "text/css"),
    ("iotanav.js",   "application/javascript"),     # shared menu bar
    ("bootstrap.min.css", "text/css"),              # built by scripts/webui-bootstrap
    ("bootstrap.min.js",  "application/javascript"),
    ("uplot.min.css", "text/css"),                  # Graph+ charts (uPlot, MIT)
    ("uplot.min.js",  "application/javascript"),
]

project = env.subst("$PROJECT_DIR")
sd = os.path.normpath(os.path.join(project, "..", "SD"))
out_dir = os.path.join(env.subst("$PROJECT_WORKSPACE_DIR"), "generated", "webui")
os.makedirs(out_dir, exist_ok=True)

digest = hashlib.sha256()
parts, table = [], []
for i, (name, ctype) in enumerate(FILES):
    raw = open(os.path.join(sd, name), "rb").read()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    digest.update(name.encode() + b"\0" + raw)
    body = ",".join("0x%02x" % b for b in gz)
    parts.append("static const char webui_n%d[] PROGMEM = \"%s\";\n" % (i, name))
    parts.append("static const char webui_t%d[] PROGMEM = \"%s\";\n" % (i, ctype))
    parts.append("static const uint8_t webui_d%d[] PROGMEM = {%s};\n" % (i, body))
    table.append("  {webui_n%d, webui_t%d, webui_d%d, %d, %d},   // %s\n" % (i, i, i, len(gz), len(raw), name))

header = (
    "// Generated by scripts/embed_webui.py from SD/ - do not edit.\n"
    "#pragma once\n#include <stdint.h>\n\n"
    "struct webuiFile { const char* name; const char* type; const uint8_t* gz; uint32_t gzLen; uint32_t len; };\n"
    "#define WEBUI_ID \"%s\"            // SHA-256 prefix of the embedded files\n"
    "#define WEBUI_COUNT %d\n\n" % (digest.hexdigest()[:16], len(FILES))
    + "".join(parts)
    + "\nstatic const webuiFile webuiFiles[WEBUI_COUNT] = {\n" + "".join(table) + "};\n"
)
path = os.path.join(out_dir, "webui_embedded.h")
if not os.path.exists(path) or open(path).read() != header:
    open(path, "w").write(header)
    print("embed_webui: %d files, %d bytes gzipped" % (len(FILES), sum(int(t.split(",")[3]) for t in table)))

env.Append(CPPDEFINES=["IOTAWATT_EMBED_WEBUI"], CPPPATH=[out_dir])
